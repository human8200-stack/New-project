    "JSON 배열만 답한다. 다른 말은 쓰지 않는다. n은 이미지 번호다.",
    "예: [{\"n\":1,\"desc\":\"주방 전체, 낮\",\"seen\":\"화이트 상부장 없는 벽, 우드 하부장, 밝은 상판\",\"privacy\":[]}]"
