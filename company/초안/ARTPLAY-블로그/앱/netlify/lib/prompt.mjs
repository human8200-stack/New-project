export function consentText(v) { return CONSENT[v] || CONSENT.photo; }
export function kindText(v) { return KIND[v] || KIND.review; }

function clean(v, max) {
  if (typeof v !== "string") return "";
  // 줄바꿈·제어 글자를 없애고 길이를 자른다 (입력 형식이 깨지지 않게)
  return v.replace(/[\u0000-\u001f\u007f]+/g, " ").replace(/\s+/g, " ").trim().slice(0, max);
}
function list(v, max) {
  return Array.isArray(v) ? v.map(x => clean(x, 30)).filter(Boolean).slice(0, max) : [];
}
function tagsLine(v) {
  const t = clean(v, 120).split(/\s+/).filter(Boolean).map(x => "#" + x.replace(/^#+/, "").replace(/[^0-9A-Za-z가-힣_]/g, "")).filter(x => x.length > 1).slice(0, 4);
  return t.length ? t.join(" ") : DEFAULT_TAGS;
}

export function buildInput(f, photos) {
  f = f || {};
  const s = f.shop || {};
  const shop = f.type === "shop";
  const spaces = list(f.spaces, 8);
  const works = list(f.works, 8);
  const region = f.consent === "region" ? clean(f.region, 30) : "";
  const size = clean(f.size, 20);
  const cost = clean(f.cost, 40);
  const shopName = shop && f.nameOk === "yes" ? clean(f.shopName, 40) : "";
  const info = [
    ["상담 지역", clean(s.area, 60)],
    ["시공 방식", clean(s.direct, 60)],
    ["하자보수", clean(s.warranty, 60)],
    ["업체 등록", clean(s.license, 60)],
    ["상담 준비물", clean(s.prep, 80)]
  ].filter(x => x[1]);
  const lines = [
    "인테리어 종류: " + (shop ? "상점(상업 공간)" : "집(주거 공간)"),
    (shop ? "업종: " : "공간 종류: ") + (spaces.join(", ") || "(없음)"),
    "공사 종류: " + (works.join(", ") || "(없음 — 메모와 사진에서 알 수 있으면 그대로, 모르면 쓰지 않는다)"),
    "평수: " + (size && size !== "모름" ? size : "(없음)"),
    "기간: " + (clean(f.period, 30) || "(없음)"),
    "지역: " + (region || "(없음)"),
    "게시 동의: " + consentText(f.consent)
  ];
  if (shop) {
    lines.push("가게 이름 공개: " + (shopName ? "사장님 동의" : "동의 없음 — 가게 이름을 쓰지 않는다"));
    lines.push("가게 이름: " + (shopName || "(없음)"));
    lines.push("좌석 수: " + (clean(f.seats, 20) || "(없음)"));
    lines.push("영업 중 공사: " + (SHOP_LIVE[f.liveIn] || "(없음)"));
  } else {
    lines.push("살면서 공사: " + (LIVE[f.liveIn] || "(없음)"));
  }
  lines.push(
    "글 종류: " + kindText(f.kind),
    "협찬·할인: " + (PERK[f.perk] || PERK.none),
    "비용: " + (cost || "(없음)"),
    (shop ? "사장님이 한 말: " : "고객이 한 말: ") + (clean(f.quote, 160) || "(없음)"),
    "메모 (" + (shop ? "고민·콘셉트·자재·설비·신경 쓴 것" : "고민·자재·신경 쓴 것") + "): " + (clean(f.memo, 400) || "(없음)"),
    "ARTPLAY 안내: " + (info.length ? info.map(x => x[0] + " = " + x[1]).join(" / ") : "(없음)"),
    "고정 해시태그: " + tagsLine(s.tags),
    "사진 설명:"
  );
  if (!photos || !photos.length) lines.push(" (사진 없음 — 본문에 사진 자리를 만들지 않는다)");
  else photos.forEach((p, i) => {
    const side = p.side === "후" ? "후" : p.side === "공사 중" ? "공사 중" : "전";
    const desc = clean(p.desc, 60) || (side + " 사진");
    const seen = clean(p.seen, 120);
    lines.push(" " + (i + 1) + ". " + side + " - " + desc + (seen ? " (보이는 것: " + seen + ")" : ""));
  });
  return lines.join("\n") + "\n\n위 지시문의 출력 형식 그대로, [제목] [본문] [해시태그] [확인할 점] 네 칸만 써라.";
}
