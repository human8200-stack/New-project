// ---------- 화면 입력값 → AI에게 주는 입력 ----------
function clean(v, max) {
  if (typeof v !== "string") return "";
  return v.replace(/[\u0000-\u0008\u000b-\u001f\u007f]+/g, " ").replace(/[ \t]+/g, " ").trim().slice(0, max);
}
function oneLine(v, max) { return clean(v, max).replace(/\s+/g, " "); }
function tagsLine(v) {
  const t = oneLine(v, 120).split(/\s+/).filter(Boolean).map(x => "#" + x.replace(/^#+/, "").replace(/[^0-9A-Za-z가-힣_]/g, "")).filter(x => x.length > 1).slice(0, 4);
  return t.length ? t.join(" ") : DEFAULT_TAGS;
}

// f = { topic, hanmadi, manuscript, next, source, tags }, photos = [{ desc, text }]
export function buildInput(f, photos) {
  f = f || {};
  const lines = [
    "주제: " + (oneLine(f.topic, 120) || "(없음)"),
    "회장님 한마디: " + (oneLine(f.hanmadi, 400) || "(없음 — 지어내지 말고 " + HANMADI_SLOT + " 자리로 비워 둔다)"),
    "다음 노트 예고: " + (oneLine(f.next, 120) || "(없음 — 다음 노트 칸을 뺀다)"),
    "출처: " + (oneLine(f.source, 120) || DEFAULT_SOURCE),
    "고정 태그: " + tagsLine(f.tags),
    "",
    "원고 (회사가 만든 노트 글):",
    clean(f.manuscript, 8000) || "(없음 — 누구나 아는 기본 설명만 쓰고, 확인할 점에 적는다)",
    "",
    "사진·카드 (번호대로 본문 알맞은 자리에 \"📷 사진 n\" 줄을 한 번씩 넣는다):"
  ];
  if (!photos || !photos.length) lines.push(" (없음)");
  else photos.slice(0, 10).forEach((p, i) => {
    const t = oneLine(p.text, 400);
    lines.push(" " + (i + 1) + ". " + (oneLine(p.desc, 60) || "사진") + (t ? " — 적힌 글·보이는 것: " + t : ""));
  });
  lines.push("", "위 지시문의 출력 형식 그대로, [제목] [본문] [태그] [확인할 점] 네 칸만 써라.");
  return lines.join("\n");
}
