function clean(v, max) {
  if (typeof v !== "string") return "";
  return v.replace(/[\u0000-\u0008\u000b-\u001f\u007f]+/g, " ").replace(/[ \t]+/g, " ").trim().slice(0, max);
}
function oneLine(v, max) { return clean(v, max).replace(/\s+/g, " "); }
function tagsLine(v) {
  const t = oneLine(v, 120).split(/\s+/).filter(Boolean).map(x => "#" + x.replace(/^#+/, "").replace(/[^0-9A-Za-z가-힣_]/g, "")).filter(x => x.length > 1).slice(0, 4);
  return t.length ? t.join(" ") : DEFAULT_TAGS;
}

